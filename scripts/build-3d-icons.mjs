#!/usr/bin/env node
/**
 * Builds the optimized 3D "clay/color" icon set that ships in public/3d/.
 *
 * Source: raw PNGs downloaded from the 3dicons.co CC0 icon pack
 * (https://github.com/realvjy/3dicons, CDN-hosted originals) into
 * assets-src/3d-icons/<name>.png (deliberately OUTSIDE public/ — Vite
 * copies public/ verbatim into dist/, so raw multi-hundred-KB originals
 * must not live under public/3d/ or they'd ship to both web and Android).
 * See public/3d/LICENSE.md for the verbatim license text and
 * public/3d/manifest.json for per-icon provenance.
 *
 * This script is idempotent: re-running it regenerates every output file
 * deterministically from the same source PNGs (no network access, no
 * randomness) and reprints the size table.
 *
 * Output, per icon <name> in assets-src/3d-icons/<name>.png:
 *   public/3d/<name>.webp      160x160 (1x), quality 82, no metadata
 *   public/3d/<name>@2x.webp   320x320 (2x), quality 82, no metadata
 *
 * Also (re)writes, for the default "color" style ONLY:
 *   public/3d/manifest.json        [{name, width, height, bytes1x, bytes2x, source, license, style}]
 *   src/lib/clayIcons.generated.ts export const CLAY_ICONS = {...} as const
 *
 * A second style variant can be built alongside the default without
 * touching either of those files, via --style=<name>:
 *   node scripts/build-3d-icons.mjs --style=gradient
 * reads assets-src/3d-icons/gradient/<name>.png and writes
 * public/3d/gradient/<name>.webp + <name>@2x.webp + public/3d/gradient/manifest.json
 * (same sizing/quality settings; NO src/lib/clayIcons.generated.ts write —
 * that file's shape is owned by the default color style only). This is not
 * generated by default — only on explicit request.
 *
 * Usage:
 *   node scripts/build-3d-icons.mjs                  # default "color" style
 *   node scripts/build-3d-icons.mjs --style=gradient  # extra "gradient" style
 *   npm run build:3d
 *   npm run build:3d -- --style=gradient
 */

import { readdirSync, statSync, mkdirSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname, basename, extname } from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const __dirname = dirname(fileURLToPath(import.meta.url));
const repoRoot = join(__dirname, '..');

// --style=<name> (or `--style <name>`) selects a non-default source/output
// pair. The default "color" style keeps its flat paths (public/3d/ root,
// assets-src/3d-icons/ root) so it's what ships without any flag.
const styleArg = process.argv.slice(2).reduce((found, arg, i, arr) => {
  if (found) return found;
  if (arg.startsWith('--style=')) return arg.slice('--style='.length);
  if (arg === '--style') return arr[i + 1] ?? null;
  return null;
}, null);
const STYLE = styleArg || 'color';
const isDefaultStyle = STYLE === 'color';

const srcDir = isDefaultStyle
  ? join(repoRoot, 'assets-src', '3d-icons')
  : join(repoRoot, 'assets-src', '3d-icons', STYLE);
const outDir = isDefaultStyle
  ? join(repoRoot, 'public', '3d')
  : join(repoRoot, 'public', '3d', STYLE);
const manifestPath = join(outDir, 'manifest.json');
const tsOutPath = join(repoRoot, 'src', 'lib', 'clayIcons.generated.ts');

const SIZE_1X = 160;
const SIZE_2X = 320;
const WEBP_QUALITY = 82;

const SOURCE_PACK = `https://3dicons.co (realvjy/3dicons, ${STYLE} style, dynamic angle)`;
const LICENSE = 'CC0-1.0';

// name -> upstream 3dicons.co file-slug, for manifest provenance.
const SLUG_MAP = {
  coins: '3d-coin',
  receipt: 'file-text',
  chat: 'chat-bubble',
  handshake: 'thumb-up',
  wallet: 'wallet',
  card: 'card',
  piggybank: 'money-bag',
  calendar: 'calender',
  bell: 'megaphone',
  gift: 'gift',
  // NOTE: there is deliberately no `people` here. It was a second name for
  // the SAME upstream `boy` art as `person` (byte-identical output), so a
  // caller reaching for "a group of people" silently got one figure. The
  // pack has no multi-person art at all; `chat` (two overlapping speech
  // bubbles) is what the group surfaces use instead.
  chart: 'chart',
  shield: 'sheild',
  target: 'target',
  phone: 'mobile',
  trophy: 'trophy',
  pot: 'bucket',
  sparkle: 'star',
  plus: 'plus',
  link: 'link',
  key: 'key',
  money: 'money',
  bag: 'bag',
  calculator: 'calculator',
  cup: 'tea-cup',
  person: 'boy',
  person2: 'girl',
  alarm: 'clock',
  tick: 'tick',
  lock: 'lock',
};

function fmtBytes(n) {
  return `${(n / 1024).toFixed(1)} KB`;
}

async function buildOne(name) {
  const srcPath = join(srcDir, `${name}.png`);
  const out1x = join(outDir, `${name}.webp`);
  const out2x = join(outDir, `${name}@2x.webp`);

  const pipeline1x = sharp(srcPath)
    .resize(SIZE_1X, SIZE_1X, { fit: 'contain', background: { r: 0, g: 0, b: 0, alpha: 0 } })
    .webp({ quality: WEBP_QUALITY, effort: 6 });
  const pipeline2x = sharp(srcPath)
    .resize(SIZE_2X, SIZE_2X, { fit: 'contain', background: { r: 0, g: 0, b: 0, alpha: 0 } })
    .webp({ quality: WEBP_QUALITY, effort: 6 });

  // sharp strips EXIF/ICC/XMP metadata by default unless .withMetadata() is
  // called, so no extra step is needed to keep files metadata-free.
  await pipeline1x.toFile(out1x);
  await pipeline2x.toFile(out2x);

  const bytes1x = statSync(out1x).size;
  const bytes2x = statSync(out2x).size;

  return { name, width: SIZE_1X, height: SIZE_1X, bytes1x, bytes2x };
}

async function main() {
  if (!existsSync(srcDir)) {
    console.error(`Source directory not found: ${srcDir}`);
    console.error(`Populate ${srcDir} with <name>.png files before running this script.`);
    process.exit(1);
  }

  const sourceFiles = readdirSync(srcDir).filter((f) => extname(f).toLowerCase() === '.png');
  if (sourceFiles.length === 0) {
    console.error(`No .png files found in ${srcDir}`);
    process.exit(1);
  }

  mkdirSync(outDir, { recursive: true });

  const results = [];
  for (const file of sourceFiles) {
    const name = basename(file, '.png');
    const result = await buildOne(name);
    results.push(result);
  }

  results.sort((a, b) => a.name.localeCompare(b.name));

  // --- manifest.json ---
  const manifest = results.map((r) => ({
    name: r.name,
    width: r.width,
    height: r.height,
    bytes1x: r.bytes1x,
    bytes2x: r.bytes2x,
    source: SLUG_MAP[r.name]
      ? `${SOURCE_PACK} — icon "${SLUG_MAP[r.name]}"`
      : SOURCE_PACK,
    license: LICENSE,
    style: STYLE,
  }));
  writeFileSync(manifestPath, JSON.stringify(manifest, null, 2) + '\n', 'utf8');

  // --- src/lib/clayIcons.generated.ts ---
  // Only the default "gradient" style owns this file — an alternate style
  // build (e.g. --style=color) must never touch it.
  if (isDefaultStyle) {
    const tsLines = [
      '// GENERATED FILE — do not hand-edit.',
      '// Regenerate with: npm run build:3d (scripts/build-3d-icons.mjs)',
      '//',
      '// Source assets: public/3d/<name>.webp (1x, 160px) and public/3d/<name>@2x.webp',
      '// (2x, 320px). See public/3d/manifest.json for per-icon provenance and',
      '// public/3d/LICENSE.md for the license text (CC0-1.0, 3dicons.co).',
      '',
      'export const CLAY_ICONS = {',
      ...results.map((r) => `  ${r.name}: { w: ${r.width}, h: ${r.height} },`),
      '} as const;',
      '',
      'export type ClayIconName = keyof typeof CLAY_ICONS;',
      '',
    ];
    mkdirSync(dirname(tsOutPath), { recursive: true });
    writeFileSync(tsOutPath, tsLines.join('\n'), 'utf8');
  }

  // --- size table ---
  const nameWidth = Math.max(...results.map((r) => r.name.length), 4);
  console.log(`Built ${results.length} icons (style: ${STYLE}) -> ${outDir}`);
  console.log('');
  console.log(`${'name'.padEnd(nameWidth)}  1x        2x        status`);
  console.log('-'.repeat(nameWidth + 34));
  let overBudget = 0;
  for (const r of results) {
    const over1x = r.bytes1x > 25 * 1024;
    const over2x = r.bytes2x > 60 * 1024;
    const status = over1x || over2x ? 'OVER BUDGET' : 'ok';
    if (over1x || over2x) overBudget++;
    console.log(
      `${r.name.padEnd(nameWidth)}  ${fmtBytes(r.bytes1x).padEnd(8)}  ${fmtBytes(r.bytes2x).padEnd(8)}  ${status}`
    );
  }
  console.log('');
  console.log(`manifest: ${manifestPath}`);
  if (isDefaultStyle) {
    console.log(`types:    ${tsOutPath}`);
  }
  if (overBudget > 0) {
    console.log('');
    console.log(`${overBudget} icon(s) exceed the 25 KB (1x) / 60 KB (2x) budget — see table above.`);
  }
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
